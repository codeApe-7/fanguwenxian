// 神通库。
//
// 一式神通 = 若干个「效果」的组合，而不是一个写死的类型——
// 于是「造成伤害 + 附灼烧 + 让对方下两回合易伤」这种事，只要填三条 effects。
//
// 三条设计铁律（战斗系统据此结算）：
//   1. 消耗恒定：升级只涨威力，`cost` 五级不变——成长的意义是「把少数几式练厚」。
//   2. 后继无力：连续施展同一式，威力逐级衰减，换招即复原——堵死「找到最优解然后无脑重复」。
//   3. 五行相生即【连击】：上一式的属性生本式属性，伤害加成——轮换本身就是收益。
//
// 文字游戏没有画面，`flavor` 就是画面：每式一句，施展时打在战报上。

import type { Element } from '../content.js';

/** 效果类型。value 的含义随 kind 而变，见每一项后的注释。 */
export type EffectKind =
  | 'dmg'      // 直接伤害：value = 攻击的百分比（100 = 一倍攻击）
  | 'dot'      // 持续伤害：每回合 攻击 × value% × 层数，共 turns 回合
  | 'heal'     // 回复气血：value = 最大气血的百分比
  | 'regen'    // 持续回血：每回合回 value% 最大气血，共 turns 回合
  | 'shield'   // 护罩：吸收 value% 最大气血的伤害，破了才掉血
  | 'drain'    // 吸血：本式造成伤害的 value% 转为自身气血
  | 'buffAtk'  // 战意：本场攻击 +value%
  | 'weaken'   // 削敌：敌方攻击 −value%（本场）
  | 'vuln'     // 易伤：敌方受到的伤害 +value%，共 turns 回合
  | 'guard'    // 减伤：自身受到的伤害 −value%，共 turns 回合
  | 'thorn'    // 反伤：受击时反弹 value% 伤害，共 turns 回合
  | 'dodge'    // 身法：闪避几率 +value%，共 turns 回合
  | 'stun'     // 定身：敌方 turns 回合不能行动
  | 'qi'       // 聚气：立即回 value 点灵气
  | 'sap'      // 滞气：夺去敌方 value 点灵气，绝技就发不出来
  | 'escape'   // 遁法：必定脱身
  | 'cleanse'; // 净化：清除自身全部负面状态

export interface SpellEffect {
  kind: EffectKind;
  value: number;
  turns?: number;   // 持续回合，缺省 1
  stacks?: number;  // 叠加层数（dot 专用），缺省 1
}

export interface SpellDef {
  name: string;
  element: Element | '无';   // 无属性＝身法/神魂/遁术，不吃相生相克
  tier: 1 | 2 | 3 | 4;       // 术 / 法 / 神通 / 仙法
  cost: number;              // 灵气消耗，★五级恒定
  effects: SpellEffect[];
  desc: string;              // 菜单一行功效
  flavor: string;            // ★ 施展时的画面
  price?: number;            // 玉简售价（缺省＝不售，只能靠功法/机缘/剧情）
  sect?: string;             // 宗门专属：仅该宗藏经阁可兑换，坊市无货
}

export const SPELL_TIER_NAMES = ['', '术', '法', '神通', '仙法'];

/** 神通等级 1~5。 */
export const SPELL_MAX_LV = 5;

/** 五级威力倍率，增幅递增（×1.30 → ×1.39）——与其点五式到三级，不如把一式点满。 */
export const SPELL_LV_MULT = [1, 1.3, 1.7, 2.3, 3.2];

/** 升到下一级所需悟道点（下标＝当前等级）。升满一式共 25 点。 */
export const SPELL_LV_COST = [0, 2, 4, 7, 12];

/** 后继无力：连续施展同一式的威力倍率，换招即复原。 */
export const FATIGUE = [1, 0.6, 0.36, 0.2, 0.1];

/**
 * 疗伤 / 护罩 / 生机这类「续航」效果的等级曲线——比伤害平缓得多。
 *
 * 伤害按攻击的百分比结算，吃满 SPELL_LV_MULT（×3.2）只是「一击更重」；
 * 续航却是按**自身气血的百分比**结算，同样乘 3.2 就意味着一式满级疗伤
 * 恢复 192% 气血——任何疗伤式到五级都等于「回满血」，续航从此不设上限。
 * 实测后果：九重雷劫把雷威调到三倍，备足的与仓促的仍然 20/20 全部飞升，
 * 因为撑不撑得住根本不由积累决定，而由「你有没有点满一式疗伤」决定。
 */
export const SPELL_LV_SUSTAIN = [1, 1.1, 1.2, 1.3, 1.4];

/** 某一级的威力倍率（等级越界自动夹紧）。 */
export function spellPower(lv: number): number {
  return SPELL_LV_MULT[Math.max(0, Math.min(SPELL_MAX_LV - 1, lv - 1))];
}

/** 某一级的续航倍率（疗伤/护罩/生机用，等级越界自动夹紧）。 */
export function spellSustain(lv: number): number {
  return SPELL_LV_SUSTAIN[Math.max(0, Math.min(SPELL_MAX_LV - 1, lv - 1))];
}

