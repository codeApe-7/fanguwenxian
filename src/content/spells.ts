/** 某一品阶的全部神通名。 */
export function spellsOfTier(tier: number): string[] {
  return Object.keys(SPELLS).filter((n) => SPELLS[n].tier === tier);
}

/** 玉简售价（不售返回 null）。 */
export function jadeSlipPrice(name: string): number | null {
  return SPELLS[name]?.price ?? null;
}
