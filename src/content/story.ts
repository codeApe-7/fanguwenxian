// 主线剧情节点库：调度模型 + 四条剧本线 + 全剧本共用的系统叙事节点。
//
// 设计要点（借鉴成熟修仙游戏的「调度层」思路，文案全部原创）：
// - 节点不再按单调下标线性播放，而是带触发窗（年龄窗/境界窗）+ flag 前置/互斥，
//   由 core/storyline.ts 每年扫描，一年至多触发一节点。
// - 「窗口关闭即永久错过」，并配错过反馈文案（missText）——玩家要意识到自己错过了什么，
//   取舍才成立，二周目才有意义。
// - 选择写 flag，后续节点用 require/exclude 读 flag——同一抉择在几百年后仍有回响。
// - when() 承接已有系统（丹毒/道侣/宗主/叛宗/寿元），让系统层进入叙事。
// - 文案分层：title 是指路牌（短），text 是叙事，log 是大事记条目（立传用）。

import type { GameState } from '../types.js';

// ---- 数据模型 ----

export interface StoryEffects {
  spirit?: number;
  heart?: number;
  cult?: number;
  life?: number;                    // 寿元增减
  toxin?: number;                   // 丹毒增减
  pill?: string;
  material?: Record<string, number>;
  skill?: string;                   // 解锁副业
  technique?: string;               // 习得功法（入库不改主修）
  fragment?: string;                // 获得功法残篇 ×1
  treasure?: string;                // 获得法宝（直接换装）
  heroine?: string;                 // 专属女主登场（对应 SCENARIO_HEROINES）
  favor?: Record<string, number>;   // 指定红颜好感增减（按姓名）
  flags?: Record<string, number>;   // flag 累加
  pardon?: boolean;                 // 解除旧宗追杀
  log?: string;                     // 追加大事记
}

export interface StoryCombat {
  intro?: string;          // 战斗开场白（{enemy} 占位）
  boost?: number;          // 敌人等级加成
  winText: string[];
  loseText: string[];
  winEffects?: StoryEffects;
  loseEffects?: StoryEffects;
}

export interface StoryChoice {
  label: string;
  result: string[];
  effects?: StoryEffects;
  combat?: StoryCombat;
}

/** flag 条件：默认 op '>='、value 1，即「flag 已立」。 */
export interface FlagReq {
  flag: string;
  op?: '>=' | '<' | '=';
  value?: number;
}

export interface StoryNode {
  id: string;
  scenario?: string;       // 所属剧本；缺省 = 全剧本共用
  title: string;           // 指路牌（【主线】标题 & 大事记缺省文本）
  minAge?: number;
  maxAge?: number;         // 年龄窗上限（过则永久错过）
  minRealm?: number;
  maxRealm?: number;       // 境界窗上限（冲过头也会错过——修得快未必全是好事）
  require?: FlagReq[];     // 前置 flag（全部满足）
  exclude?: string[];      // 互斥 flag（任一 ≥1 则永不触发，不算「错过」）
  when?: (state: GameState) => boolean; // 系统条件（丹毒/道侣/宗主等）
  text: string[];
  choices?: StoryChoice[];
  effects?: StoryEffects;  // 无分支时的固定效果
  missText?: string[];     // 错过反馈（窗口关闭当年播报一次）
  log?: string;            // 大事记条目（缺省用 title）
}

